export function translateUI(key: string, locale: Locale): string {
  if (locale === "en") return key;
  return DICTIONARY[locale]?.[key] ?? key;
}

export function formatLocalizedDate(date: Date, locale: Locale): string {
  const bcp47 = LOCALE_OPTIONS.find((l) => l.code === locale)?.bcp47 ?? "en-IN";
  return new Intl.DateTimeFormat(bcp47, {
    day: "2-digit",
    month: "short",
    year: "numeric",
  }).format(date);
}
